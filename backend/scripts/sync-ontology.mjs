// Generate amplify/functions/graph-shared/ontology.generated.ts from
// packages/ontology, the source of truth (ADR-0007). Amplify's backend build
// installs backend/ only, so the Lambdas cannot read the workspace package at
// build time; they carry this generated copy. graph-shared/validate.test.ts
// fails when it drifts.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(here, "../../packages/ontology");
const files = {
  TBOX: "tbox/app.ttl",
  CONCEPTS: "tbox/app-concepts.ttl",
  SHAPES: "shapes/app-shapes.ttl",
};
let out = "// GENERATED by backend/scripts/sync-ontology.mjs from packages/ontology. Do not edit.\n";
for (const [name, rel] of Object.entries(files)) {
  out += `export const ${name} = ${JSON.stringify(fs.readFileSync(path.join(src, rel), "utf8"))};\n`;
}
const dest = path.resolve(here, "../amplify/functions/graph-shared/ontology.generated.ts");
fs.writeFileSync(dest, out);
console.log(`  wrote ${path.relative(process.cwd(), dest)}`);
